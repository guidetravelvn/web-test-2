document.addEventListener('DOMContentLoaded', () => {
  applyLang();
  // Mark active lang button
  const cur = localStorage.getItem('gt_lang') || 'vi';
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active-lang', b.dataset.lang === cur));
});
