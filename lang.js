// ===== HELPERS =====
function t(key) {
  const lang = localStorage.getItem('gt_lang') || 'vi';
  return TRANS[lang]?.[key] ?? TRANS.vi[key] ?? key;
}

function fmtPrice(n) {
  const lang = localStorage.getItem('gt_lang') || 'vi';
  if (lang === 'en') return '~$' + Math.round(n / 25000);
  return new Intl.NumberFormat('vi-VN').format(n) + 'đ';
}

function fmtVNDInput(input) {
  const raw = input.value.replace(/\./g, '').replace(/\D/g, '');
  input.value = raw ? new Intl.NumberFormat('vi-VN').format(Number(raw)) : '';
}

function rawVND(input) {
  return Number((input?.value || '').replace(/\./g, '')) || '';
}

function setLang(lang) {
  localStorage.setItem('gt_lang', lang);
  document.documentElement.lang = lang;
  applyLang();
  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active-lang', b.dataset.lang === lang));
}

function applyLang() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    const val = t(key);
    if (attr) el.setAttribute(attr, val);
    else el.innerHTML = val;
  });
}

